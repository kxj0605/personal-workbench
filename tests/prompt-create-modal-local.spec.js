import { test, expect } from '@playwright/test';

test('提示词弹窗支持取消、保存、分类和刷新恢复', async ({ page }) => {
  await page.goto('/?workspace-preview&workspace-tab=script-prompts&nav=sidebar-v1');
  const hero = page.locator('.workspace-prompt-library-hero');
  const add = hero.getByRole('button', { name: '添加提示词', exact: true });
  const dialog = page.getByRole('dialog', { name: '保存新提示词', exact: true });
  const cards = page.locator('.creator-prompt');
  await expect(page.locator('.creator-materials-save')).toHaveCount(0);
  const scriptPosition = await hero.getByRole('button', { name: '脚本', exact: true }).boundingBox();
  const addPosition = await add.boundingBox();
  expect(addPosition.x).toBeGreaterThan(scriptPosition.x + scriptPosition.width);
  expect(Math.abs(addPosition.y - scriptPosition.y)).toBeLessThan(8);

  await add.click();
  await expect(dialog).toBeVisible();
  await expect(dialog.getByLabel('素材类型')).toHaveValue('script');
  await expect(dialog.getByLabel('素材类型')).toBeDisabled();
  await dialog.getByRole('button', { name: '保存提示词', exact: true }).click();
  await expect(dialog).toBeVisible();
  await expect(cards).toHaveCount(0);
  await dialog.locator('textarea').fill('用于验证弹窗的脚本提示词');
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(add).toBeFocused();
  await expect(cards).toHaveCount(0);
  await add.click();
  await expect(dialog.locator('textarea')).toHaveValue('用于验证弹窗的脚本提示词');
  await dialog.getByLabel('来源分类').fill('自己整理');
  await dialog.getByPlaceholder('标签，用逗号分隔').fill('骨架，改编');
  await dialog.getByRole('button', { name: '保存提示词', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(cards).toHaveCount(1);
  await expect(cards).toContainText('用于验证弹窗的脚本提示词');
  await expect(cards).toContainText('自己整理');

  await hero.getByRole('button', { name: '我的提示词', exact: true }).click();
  await expect(page.locator('.creator-materials-save')).toHaveCount(0);
  await expect(cards).toHaveCount(1);
  await add.click();
  await expect(dialog.getByLabel('素材类型')).toBeEnabled();
  await dialog.getByLabel('素材类型').selectOption('custom');
  await dialog.getByLabel('自定义类型').fill('分镜模板');
  await dialog.locator('textarea').fill('用于验证弹窗的自定义提示词');
  await dialog.getByRole('button', { name: '保存提示词', exact: true }).click();
  await expect(cards).toHaveCount(2);
  await expect(cards.first()).toContainText('分镜模板');
  await hero.getByRole('button', { name: '脚本', exact: true }).click();
  await expect(cards).toHaveCount(1);
  await page.reload();
  await expect(cards).toHaveCount(1);
  await expect(cards).toContainText('用于验证弹窗的脚本提示词');

  await hero.getByRole('button', { name: '图片修改', exact: true }).click();
  await expect(page.locator('.image-edit-method-card')).toHaveCount(29);
  await hero.getByRole('button', { name: '脚本', exact: true }).click();
  await add.click();
  await page.screenshot({ path: 'test-results/prompt-create-dialog-desktop.png' });
  await dialog.getByRole('button', { name: '关闭添加提示词', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(add).toBeVisible();
  const heroSize = await hero.evaluate(element => ({ width: element.clientWidth, scroll: element.scrollWidth }));
  expect(heroSize.scroll).toBeLessThanOrEqual(heroSize.width);
  await add.click();
  await expect(dialog).toBeVisible();
  const dialogSize = await dialog.evaluate(element => ({ width: element.clientWidth, scroll: element.scrollWidth }));
  expect(dialogSize.scroll).toBeLessThanOrEqual(dialogSize.width);
  await page.screenshot({ path: 'test-results/prompt-create-dialog-mobile.png' });
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
});
