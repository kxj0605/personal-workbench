import { test, expect } from '@playwright/test';

const url = '/?workspace-preview&workspace-tab=creator-materials&nav=sidebar-v1';
const categoryNav = page => page.getByRole('navigation', { name: '提示词大类', exact: true });
const cardByTitle = (page, title) => page.locator('.ph-card').filter({ has: page.getByRole('heading', { name: title, exact: true }) });

test('已有浏览器数据中的图片修改改名为图片，内容与分类关联不变', async ({ page }) => {
  await page.goto(url);
  const before = await page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem('prompt-hub-workspace-v1'));
    data.categories.find(item => item.value === 'image-edit').label = '图片修改';
    delete data.imageCategoryLabelVersion;
    localStorage.setItem('prompt-hub-workspace-v1', JSON.stringify(data));
    return { prompts: data.prompts, children: data.categories.find(item => item.value === 'image-edit').subcategories };
  });
  await page.reload();
  await categoryNav(page).getByRole('button', { name: '图片', exact: true }).click();
  await expect(page.locator('.ph-card')).toHaveCount(39);
  await expect(page.locator('.ph-category').first()).toHaveText('图片');
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem('prompt-hub-workspace-v1')));
  expect(after.prompts).toEqual(before.prompts);
  expect(after.categories.find(item => item.value === 'image-edit').subcategories).toEqual(before.children);
});

