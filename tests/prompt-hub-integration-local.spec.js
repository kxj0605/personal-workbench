test('新增类别和二级分类、新建编辑取消删除，以及分类删除转移', async ({ page }) => {
  await page.goto(url);
  await page.getByRole('button', { name: '分类管理', exact: true }).click();
  const manager = page.getByRole('dialog', { name: '分类管理', exact: true });
  const roots = manager.getByRole('region', { name: '管理提示词类别', exact: true });
  await roots.getByRole('textbox', { name: '新类别名称', exact: true }).fill('新增类别');
  await roots.getByRole('button', { name: '新增类别', exact: true }).click();
  const children = manager.getByRole('region', { name: '管理二级分类', exact: true });
  await children.getByRole('textbox', { name: '新二级分类名称', exact: true }).fill('新增二级');
  await children.getByRole('button', { name: '新增二级分类', exact: true }).click();
  await manager.getByRole('button', { name: '关闭分类管理', exact: true }).click();
  await categoryNav(page).getByRole('button', { name: '新增类别', exact: true }).click();
  await page.getByRole('button', { name: '新建提示词', exact: true }).click();
  let editor = page.getByRole('dialog', { name: '新建提示词', exact: true });
  await editor.getByLabel('标题', { exact: true }).fill('新建内容');
  await editor.getByLabel('简介', { exact: true }).fill('简介');
  await editor.getByLabel('二级分类', { exact: true }).selectOption({ label: '新增二级' });
  await editor.getByLabel('提示词正文', { exact: true }).fill('新建正文');
  await editor.getByRole('button', { name: '保存并生效', exact: true }).click();
  await expect(page.locator('.ph-count')).toHaveText('共 1 条');
  await cardByTitle(page, '新建内容').getByRole('button', { name: /^修改提示词：/ }).click();
  editor = page.getByRole('dialog', { name: '修改提示词', exact: true });
  await editor.getByLabel('标题', { exact: true }).fill('取消的标题');
  await editor.getByRole('button', { name: '取消', exact: true }).click();
  await expect(cardByTitle(page, '新建内容')).toBeVisible();
  await page.getByRole('button', { name: '分类管理', exact: true }).click();
  await roots.getByRole('button', { name: '删除新增类别', exact: true }).click();
  await roots.getByRole('combobox').selectOption('script');
  await roots.getByRole('button', { name: '确认删除类别', exact: true }).click();
  await manager.getByRole('button', { name: '关闭分类管理', exact: true }).click();
  await categoryNav(page).getByRole('button', { name: '脚本', exact: true }).click();
  await expect(cardByTitle(page, '新建内容')).toBeVisible();
  await cardByTitle(page, '新建内容').getByRole('button', { name: /^修改提示词：/ }).click();
  await editor.getByRole('button', { name: '删除提示词', exact: true }).click();
  await editor.getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(cardByTitle(page, '新建内容')).toHaveCount(0);
  await page.reload();
  await categoryNav(page).getByRole('button', { name: '脚本', exact: true }).click();
  await expect(page.locator('.ph-card')).toHaveCount(3);
});
