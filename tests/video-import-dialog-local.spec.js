import { test, expect } from '@playwright/test';

test('旧提示词与导入流程接入，粘贴回填后检查保存，未知字段不覆盖已有链接', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.setViewportSize({ width: 1221, height: 918 });
  await page.goto('/?workspace-preview&workspace-tab=creator-benchmark&nav=sidebar-v1');
  await page.evaluate(() => localStorage.setItem('benchmark-video-prompt-douyin-v1', '自定义视频提取提示词\n视频链接：{{视频链接}}\n账号：\n点赞量：'));
  const frame = page.frameLocator('iframe[title="对标库工作区"]');
  await frame.getByRole('button', { name: '视频全景管理', exact: true }).click();
  await frame.getByRole('button', { name: '+ 录入新视频', exact: true }).click();
  await frame.locator('#form-video-url').fill('https://v.douyin.com/test/');
  await frame.getByRole('button', { name: '导入视频资料', exact: true }).click();
  await frame.getByRole('button', { name: '复制提示词', exact: true }).click();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  expect(copied).toContain('自定义视频提取提示词');
  expect(copied).toContain('https://v.douyin.com/test/');
  await frame.getByRole('button', { name: '设置视频资料提示词', exact: true }).click();
  await frame.locator('#video-prompt-editor').fill('改过的提取模板\n视频链接：{{视频链接}}');
  await frame.getByRole('button', { name: '保存提示词', exact: true }).click();
  expect(await page.evaluate(() => localStorage.getItem('benchmark-video-prompt-douyin-v1'))).toContain('改过的提取模板');
  await frame.getByRole('button', { name: '设置视频资料提示词', exact: true }).click();
  const content = '视频标题：导入验证视频\n视频标签：#报恩、重逢\n视频链接：https://v.douyin.com/import/\n账号：@导入作者\n账号链接：https://www.douyin.com/user/test\n视频时长：00:32\n发布时间：2026-10-12\n背景音乐：测试音乐\n点赞量：1.2万\n评论量：0\n收藏量：320\n转发量：20';
  await page.evaluate(text => navigator.clipboard.writeText(text), content);
  await frame.locator('#video-import-text').click();
  await page.keyboard.press('Control+V');
  await expect(frame.locator('#video-import-status')).toContainText('已回填');
  await page.screenshot({ path: 'test-results/video-import-dialog.png', fullPage: true });
  await frame.getByRole('button', { name: '返回检查', exact: true }).click();
  await expect(frame.locator('#form-video-title')).toHaveValue('导入验证视频');
  await expect(frame.locator('#form-video-likes')).toHaveValue('12000');
  await expect(frame.locator('#form-video-comments')).toHaveValue('0');
  await expect(frame.locator('#form-video-collects')).toHaveValue('320');
  await expect(frame.locator('#form-video-shares')).toHaveValue('20');
  await expect(frame.locator('#form-video-platform')).toHaveValue('抖音');
  await expect(frame.locator('#video-import-extra')).toContainText('@导入作者');
  await page.screenshot({ path: 'test-results/video-import-intake.png', fullPage: true });
  await frame.locator('#modal-video-edit').getByRole('button', { name: /保存/ }).click();
  await page.reload();
  await frame.getByRole('button', { name: '视频全景管理', exact: true }).click();
  await expect(frame.locator('#video-table-body')).toContainText('@导入作者');
  await frame.locator('#video-table-body').getByRole('button', { name: '编辑', exact: true }).click();
  await expect(frame.locator('#video-import-extra')).toContainText('测试音乐');
  await frame.getByRole('button', { name: '导入视频资料', exact: true }).click();
  await frame.locator('#video-import-text').fill('账号链接：不可用\n视频链接：不可用\n点赞量：10');
  await frame.getByRole('button', { name: '识别并回填', exact: true }).click();
  await frame.getByRole('button', { name: '返回检查', exact: true }).click();
  await expect(frame.locator('#form-video-url')).toHaveValue('https://v.douyin.com/import/');
  await expect(frame.locator('#video-import-extra')).toContainText('https://www.douyin.com/user/test');
});
